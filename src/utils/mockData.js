// 用固定種子生成偽隨機數，確保同股票同年度資料穩定一致
const seededRand = (seed) => {
  const x = Math.sin(seed + 1) * 10000;
  return x - Math.floor(x);
};

export const generateMockRoeHistory = (symbol) => {
  const currentYear = new Date().getFullYear();
  const seed = parseInt(symbol, 10);
  const baseRoe = 10 + seededRand(seed) * 20; // 10% ~ 30%

  return Array.from({ length: 10 }, (_, i) => {
    const year = currentYear - 9 + i;
    const trend = i * 0.5; // 輕微成長趨勢
    const noise = (seededRand(seed + year) - 0.5) * 6;
    const roe = Math.max(3, parseFloat((baseRoe + trend + noise).toFixed(2)));
    return { year, roe };
  });
};
